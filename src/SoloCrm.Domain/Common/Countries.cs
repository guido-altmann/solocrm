    static Countries()
    {
        ByCode = All.ToDictionary(c => c.Code, StringComparer.OrdinalIgnoreCase);
        ByName = new Dictionary<string, Country>(StringComparer.OrdinalIgnoreCase);
        foreach (var country in All)
        {
            ByName.TryAdd(country.GermanName, country);
            ByName.TryAdd(country.EnglishName, country);
        }

        foreach (var (alias, code) in Aliases)
        {
            ByName.TryAdd(alias, ByCode[code]);
        }
    }

