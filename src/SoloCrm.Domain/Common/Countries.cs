    public static bool IsValidCode(string? code) => code is { Length: 2 } && ByCode.ContainsKey(code);

    public static Country? ByIsoCode(string? code) => code is null ? null : ByCode.GetValueOrDefault(code.Trim());

    /// <summary>Recognizes a code (<c>DE</c>), a German (<c>Deutschland</c>) or English name (<c>Germany</c>) or an alias.</summary>
    public static Country? Find(string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            return null;
        }

        var trimmed = value.Trim();
        return ByCode.GetValueOrDefault(trimmed) ?? ByName.GetValueOrDefault(trimmed);
    }
